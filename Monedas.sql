FROM (
	SELECT 'Peso colombiano' AS moneda, 'COP' AS sigla
	UNION ALL
	SELECT 'Real brasileño', 'BRL'
	UNION ALL
	SELECT 'Euro', 'EUR'
	UNION ALL
	SELECT 'Yuan chino', 'CNY' 
	UNION ALL
	SELECT 'Bitcoin', 'BTC'
) AS nueva
WHERE NOT EXISTS (
	SELECT 1 FROM moneda m WHERE m.moneda = nueva.moneda
);

